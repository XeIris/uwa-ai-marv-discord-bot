// Formatting (shared by the slash commands and the AI tools)
// ---------------------------------------------------------------------------

export function formatCommitteeRoster(entries: CommitteeEntry[]): string {
  if (entries.length === 0) return 'No committee members are registered for this server yet.';

  const render = (entry: CommitteeEntry): string => {
    const name = entry.displayName ? ` — ${entry.displayName}` : '';
    return `- ${entry.title}: <@${entry.userId}>${name}`;
  };

  const execs = entries.filter((entry) => entry.isExecutive);
  const others = entries.filter((entry) => !entry.isExecutive);

  const sections: string[] = [];
  if (execs.length > 0) sections.push(`**Executive**\n${execs.map(render).join('\n')}`);
  if (others.length > 0) sections.push(`**Non-Executive**\n${others.map(render).join('\n')}`);
  return sections.join('\n\n');
}

export function formatEventList(events: EventEntry[]): string {
  if (events.length === 0) return 'No events are scheduled.';

  return events.map((event) => {
    const parts = [`**${event.name}** (id ${event.id})`];
    parts.push(`  When: ${discordTimestamp(event.startsAt)} (${discordTimestamp(event.startsAt, 'R')})`);
    if (event.endsAt) parts.push(`  Until: ${discordTimestamp(event.endsAt)}`);
    if (event.location) parts.push(`  Where: ${event.location}`);
    if (event.url) parts.push(`  Link: ${event.url}`);
    if (event.description) parts.push(`  ${event.description}`);
    return parts.join('\n');
  }).join('\n\n');
}

