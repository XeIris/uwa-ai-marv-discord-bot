let cachedConstitution: string | null = null;

/** The constitution text served to the model by recall_constitution. */
export async function getConstitution(): Promise<string> {
  if (cachedConstitution !== null) return cachedConstitution;
  try {
    cachedConstitution = await Bun.file(CONSTITUTION_PATH).text();
  } catch (err) {
    logError('[club] failed to read constitution:', err);
    return 'Error: the club constitution is unavailable right now. Tell the user you cannot look it up '
      + 'and point them at https://github.com/UWA-AI-Club/constitution instead.';
  }
  return cachedConstitution;
}

export async function runListCommittee(club: ClubContext, args: { query?: string } = {}): Promise<string> {
  try {
    const entries: CommitteeEntry[] = await club.db.committee.listByServer(club.guildId);
    const query = typeof args.query === 'string' ? args.query.trim().toLowerCase() : '';
    const filtered = query
      ? entries.filter((entry) => entry.title.toLowerCase().includes(query)
        || (entry.displayName ?? '').toLowerCase().includes(query))
      : entries;

    if (query && filtered.length === 0) {
      return `No committee role or member matches "${args.query}". Full roster:\n\n${formatCommitteeRoster(entries)}`;
    }
    return formatCommitteeRoster(filtered);
  } catch (err) {
    logError('[club] list_committee failed:', err);
    return 'Error: the committee roster could not be read right now.';
  }
}

export async function runListEvents(
  club: ClubContext,
  args: { include_past?: boolean; limit?: number } = {},
): Promise<string> {
  try {
    const rawLimit = Number(args.limit);
    const limit = Number.isFinite(rawLimit)
      ? Math.min(Math.max(Math.trunc(rawLimit), 1), EVENTS_MAX_LIMIT)
      : EVENTS_DEFAULT_LIMIT;

    const events: EventEntry[] = args.include_past === true
      ? await club.db.event.listAll(club.guildId, limit)
      : await club.db.event.listUpcoming(club.guildId, limit);

    if (events.length === 0) {
      return args.include_past === true
        ? 'No events are recorded for this server.'
        : 'No upcoming events are scheduled. (Past events exist only if include_past is set.)';
    }
    return formatEventList(events);
  } catch (err) {
    logError('[club] list_events failed:', err);
    return 'Error: the event list could not be read right now.';
  }
}
